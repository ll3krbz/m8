#!/usr/bin/env python3
"""Embed a directory of assets into a single C source file.

Usage: embed_assets.py <asset_dir> <output_c> <root_prefix>
  asset_dir   : directory tree of assets to embed
  output_c    : path to generated .c file
  root_prefix : virtual path prefix stripped from each asset name (e.g. "assets")
"""
import os
import sys


def c_ident(name):
    ident = ""
    for ch in name:
        if ch.isalnum() or ch == "_":
            ident += ch
        else:
            ident += "_"
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return ident


def main():
    if len(sys.argv) != 4:
        sys.stderr.write("usage: embed_assets.py <asset_dir> <output_c> <root_prefix>\n")
        return 1
    asset_dir = sys.argv[1]
    output_c = sys.argv[2]
    root_prefix = sys.argv[3]

    entries = []
    for root, dirs, files in os.walk(asset_dir):
        dirs.sort()
        for fname in sorted(files):
            full = os.path.join(root, fname)
            rel = os.path.relpath(full, asset_dir)
            rel = rel.replace(os.sep, "/")
            entries.append((rel, full))

    entries.sort(key=lambda e: e[0])

    with open(output_c, "w") as f:
        f.write("/* Auto-generated by embed_assets.py - do not edit. */\n")
        f.write("#include <stdint.h>\n")
        f.write("#include <stddef.h>\n")
        f.write("#include <string.h>\n")
        f.write("\n")
        f.write("struct EmbeddedAsset {\n")
        f.write("    const char* name;\n")
        f.write("    const uint8_t* data;\n")
        f.write("    size_t size;\n")
        f.write("};\n")
        f.write("\n")

        for rel, full in entries:
            ident = "asset_" + c_ident(rel)
            with open(full, "rb") as af:
                data = af.read()
            f.write("static const uint8_t %s[] = {\n" % ident)
            for i in range(0, len(data), 16):
                chunk = data[i:i + 16]
                f.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
            f.write("};\n")
            f.write("\n")

        f.write("static const struct EmbeddedAsset embedded_assets[] = {\n")
        for rel, full in entries:
            ident = "asset_" + c_ident(rel)
            with open(full, "rb") as af:
                size = len(af.read())
            f.write('    {"%s", %s, %d},\n' % (rel, ident, size))
        f.write("};\n")
        f.write("\n")
        f.write("size_t embedded_asset_count(void) {\n")
        f.write("    return sizeof(embedded_assets) / sizeof(embedded_assets[0]);\n")
        f.write("}\n")
        f.write("\n")
        f.write("const struct EmbeddedAsset* embedded_asset_at(size_t i) {\n")
        f.write("    if (i >= embedded_asset_count()) return 0;\n")
        f.write("    return &embedded_assets[i];\n")
        f.write("}\n")
        f.write("\n")
        f.write("const uint8_t* embedded_asset_find(const char* name, size_t* outSize) {\n")
        f.write("    size_t n = embedded_asset_count();\n")
        f.write("    for (size_t i = 0; i < n; ++i) {\n")
        f.write("        const struct EmbeddedAsset* a = &embedded_assets[i];\n")
        f.write("        if (strcmp(a->name, name) == 0) {\n")
        f.write("            if (outSize) *outSize = a->size;\n")
        f.write("            return a->data;\n")
        f.write("        }\n")
        f.write("    }\n")
        f.write("    if (outSize) *outSize = 0;\n")
        f.write("    return 0;\n")
        f.write("}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
